// Generates the CSS variables and the Astryx theme tokens from src/styles/palette.json, so the palette
// is edited in exactly one place. Run: npm run palette
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const palette = JSON.parse(readFileSync(join(root, "src/styles/palette.json"), "utf8"));

const block = (selector, index, extra = "") => {
  const lines = Object.entries(palette.colors).map(([name, pair]) => `  --${name}: ${pair[index]};`);
  return `${selector} {\n${extra}${lines.join("\n")}\n}`;
};

const css = [
  "/* GENERATED by scripts/gen-palette.mjs from palette.json. Do not edit by hand. */",
  "@layer legacy {",
  block(":root", 0),
  block(':root[data-theme="light"]', 1),
  "}",
  "",
].join("\n");
writeFileSync(join(root, "src/styles/palette.generated.css"), css);

// Astryx tuples are [light, dark].
const tokens = {};
for (const [token, name] of Object.entries(palette.astryxRefs)) {
  const [dark, light] = palette.colors[name];
  tokens[token] = [light, dark];
}
for (const [token, [dark, light]] of Object.entries(palette.astryxExplicit)) tokens[token] = [light, dark];

const ts = [
  "// GENERATED by scripts/gen-palette.mjs from styles/palette.json. Do not edit by hand.",
  "export const ASTRYX_COLOR_TOKENS: Record<string, [string, string]> = " + JSON.stringify(tokens, null, 2) + ";",
  "",
].join("\n");
writeFileSync(join(root, "src/lib/palette.generated.ts"), ts);
console.log("palette generated:", Object.keys(palette.colors).length, "colors,", Object.keys(tokens).length, "astryx tokens");
